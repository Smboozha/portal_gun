# ========================= физические константы (SI) ========================
hbar = 1.054571817e-34          # Дж·с
c    = 2.99792458e8             # м/с
G    = 6.67430e-11              # м³/(кг·с²)
pi   = np.pi

R0      = 0.10                  # м (конвенция r0)
T_R0    = R0 / c                # r0-единица времени, с
L_P     = np.sqrt(G * hbar / c**3)  # длина Планка, м
L_P2    = L_P**2                # длина Планка², м²

# QI-константа (в 4πr0²-единицах, r4_qi_ft.py)
C_QI = 3.0 * G * hbar / (8.0 * pi * c**3 * R0**2)
C_FR = (2160.0 / (32.0 * pi**4)) ** 0.25   # ≈0.9124

# ========================= Казимир (SI) =====================================
def eps_cas(d):
    """|ε|_Казимир, Дж/м³."""
    return pi**2 * hbar * c / (720.0 * d**4)

# ========================= FR-предел (SI) ==================================
def tau_FR_s(d):
    """τ_FR = C_FR·d/c, секунды."""
    return C_FR * d / c

# ========================= QI-предел, модифицированный T0 ==================
def tau_qi_bound(d, T0_SI, xi=1.0):
    """Максимальное время жизни ячейки d при гипотезе (1+ξ·T0):
       τ_avail = τ_FR · (1 + ξ·T0)^{1/4}."""
    return tau_FR_s(d) * (1.0 + xi * T0_SI) ** 0.25

def T0_for_lifetime(d, tau_target, xi=1.0):
    """T0_SI, нужный для τ_avail = tau_target (секунды).
       T0 = [(τ_target/τ_FR)⁴ − 1] / ξ."""
    tFR = tau_FR_s(d)
    ratio = (tau_target / tFR) ** 4
    return max(0.0, (ratio - 1.0) / xi)

def T0_crit_SI(d, xi=1.0):
    """T0_SI, при котором τ_avail = 1 с (critical for d)."""
    return T0_for_lifetime(d, 1.0, xi)

def T0_to_planck(T0_SI):
    """T0 в Planck⁻² единицах: T0_PL = T0_SI / L_P⁻²."""
    return T0_SI * L_P2

# ========================= T0 из реальных масштабов =========================
def T0_from_mass(M_kg):
    """T0 ~ 3/(2·r_s²) для SSS-гравитации (r_s=2GM/c²). В SI: м⁻²."""
    r_s = 2.0 * G * M_kg / c**2
    return 1.5 / r_s**2

# ========================= Пороговые значения ===============================
def table_thresholds(xi=1.0):
    """Таблица: T0_crit для d = 0.1, 1, 10, 100 мкм; τ = 1 с."""
    d_list = np.array([0.1, 1.0, 10.0, 100.0]) * 1e-6   # м
    rows = []
    for d in d_list:
        tFR = tau_FR_s(d)
        T0c = T0_crit_SI(d, xi)
        T0p = T0_to_planck(T0c)
        rows.append({
            "d_um": d * 1e6,
            "tau_FR_s": tFR,
            "T0_crit_SI_m_minus2": T0c,
            "T0_crit_Planck_units": T0p,
        })
    return rows

# ========================= F(T) связь ======================================
def T0_from_alpha(alpha, r0=R0):
    """T0_SI из α = T0·r0² → T0 = α/r0² [м⁻²]."""
    return alpha / r0**2

def alpha_from_T0(T0_SI, r0=R0):
    """α = T0·r0²."""
    return T0_SI * r0**2

# ========================= Объединённая формула ============================
def tau_avail_unified(d, T0_SI, xi=1.0, alpha_fT=None, r0=R0):
    """ЕДИНАЯ ФОРМУЛА: τ_avail(d, T0, ξ) = τ_FR·(1+ξ·T0)^{1/4}.
       Если задан alpha_fT (f(T)-модель), добавляется factor f(T):
       τ_eff = τ_FR · [(1+ξ·T0)·(1+22|α|)]^{1/4} для α<0.
       Возвращает (tau_avail, factors_dict)."""
    tFR = tau_FR_s(d)
    qi_factor = (1.0 + xi * T0_SI) ** 0.25

    ft_factor = 1.0
    q_eff = 0.0
    if alpha_fT is not None and alpha_fT < 0.0:
        q_eff = min(1.0, -22.0 * alpha_fT)
        ft_factor = (1.0 - q_eff) ** (-0.25) if q_eff < 1.0 else np.inf

    tau = tFR * qi_factor * ft_factor
    factors = {
        "tau_FR_s": tFR,
        "qi_factor": qi_factor,
        "ft_factor": ft_factor,
        "q_eff": q_eff,
        "tau_avail_s": tau if np.isfinite(ft_factor) else np.inf,
    }
    return tau, factors

