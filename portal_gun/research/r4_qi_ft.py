"""
R4 [АГЕНТ-2 ФИЗИКА ОГРАНИЧЕНИЙ] — Квантовые неравенства Форд-Роман для источника
Казимира в f(T)-гравитации с кручением (good-тетрада). Пересчёт жёсткости QI.
================================================================================
ФИЗИКА (по литературе, честно):

1) QI Форда-Романа (безмассовый скаляр, 4D, световая трубка, L.H.Ford &
   T.A.Roman, PRD 53 (1996) 5496 [и PRD 51 (1995) 4277], локально плоский фон):
        <ρ_smeared>  >=  -3/(32π²·τ⁴)      (ℏ=c=1, τ — время сэмплирования)
   В СИ (восстановление ℏ,c; плотность энергии):
        ε >= -3ℏ/(32π²c³τ⁴)  [Дж/м³]   <=>  ρ >= -3ℏ/(32π²c⁵τ⁴)  [кг/м³]
   В наших единицах (r0=0.1 м, t_r0=r0/c, ρ̄=4πr0²·(G/c²)ρ — нормировка R2):
        4πr0²·ρ̄ >= -C_QI/τ̄⁴ ,   C_QI = 3Gℏ/(8πc³r0²) ≈ 3.12e-69
   Следствие для Казимира (ε_Каз=−π²ℏc/(720d⁴)): QI даёт максимальное время
   жизни отрицательной энергии ячейки
        τ_FR(d) = (2160/32π⁴)^{1/4}·d/c ≈ 0.9124·d/c   (в GR, q=0).

2) В f(T) QI строго выведен ДЛЯ ПЛОСКОГО Минковского; на фоне кручения —
   только оценка. ДОПУЩЕНИЯ, при которых оценка работает, и ОСТАТОК:
   (i) материя минимально связана (спин-связи нет): объект QI — материальный
       T_μν, он от кручения НЕ меняется; кручение действует только через гео-
       метрию (сюда входит наш лагранжиан, см. R2/R3);
   (ii) локальная плоскость: τ ≪ масштаб кривизны/кручения
       (для всех наших d и τ̄ это выполняется с огромным запасом: τ̄_L~1e-15
       против t_r0~3e-10, для горловины τ~1e-27 ≪ t_r0);
   (iii) ОСТАТОК/жёсткость НЕ обнуляется, а пересчитывается: f(T) меняет
        ТРЕБУЕМУЮ материальную плотность (R2, good-тетрада, BHL (18)-(20)):
        у горловины 4πr0²ρ(x=1; α) = −(1+22α)/2. В GR (α=0) это −1/2 (экзотика);
        при α<0 требование экзотики СНИМАЕТСЯ частично (0<q<1) или полностью
        (q≥1 → ρ_req≥0, NEC по материи выполнен). QI как ОГРАНИЧЕНИЕ НА МАТЕРИЮ
        остаётся в силе; торсион снимает ЖЁСТКОСТЬ источника, а не формулу FR.
   Доля компенсации торсионом:  q(x;α) = 1 − ρ_req(x;α)/ρ_GR(x;α)
       (ρ_GR = −1/(2x⁴) — TEGR/GR-предел, x=r/r0, 4πr0²·единицы).
   Остаточная экзотика, которую обязана удержать QI: (1−q)·ε_Каз.
       τ_avail(d) = τ_FR(d)·(1−q)^{-1/4};  при q≥1 → ∞ (экзотика не требуется).
   Оценочный характер: реальная жёсткость ВЫШЕ (τ_avail — оценка СВЕРХУ), т.к.
   (a) дыхательная скалярная поляризация f(T) сама флуктуирует и может нести
       отрицательную энергию в пробе (ужесточает, учёт через ξ∈[0,1): q→(1-ξ)q);
   (b) QI вокруг горловины имеет поправки ~τ·√{|T|}, ~τ·√K фоновой геометрии;
   (c) краевые эффекты пластин. НЕ заявляем «FR отменены» — показываем, как
       торсионный вклад меняет жёсткость, и считаем числа.

3) БЕЗРАЗМЕРНЫЙ КОЭФФИЦИЕНТ НАСЫЩЕНИЯ (он же «отношение τ⁴·|ρ|·(32π²/3)»):
        R(d,τ) = (32π²c³/3ℏ)·ε_Каз(d)·τ⁴ = (32π⁴/2160)·(cτ/d)⁴ ≈ 1.4431·(cτ/d)⁴
   (не зависит от ℏ — у Казимира и QI одинаковый каркас ℏc). R≤1 ⇒ QI не
   нарушено. В GR при τ=τ_FR: R=1.000 (предел). С торсионом R_eff = (1−q).
   Примечание про энергетическую плотность через массовую ρ: R тот же самый.

4) ДВА РАЗНЫХ МАСШТАБА (важно для отчёта):
   (A) ЛАБ-ЯЧЕЙКА Казимира d∈{0.1..10 мкм}: |ρ|~1e-21..1e-29 кг/м³,
       4πr0²ρ̄(geom)~1e-49..1e-57 — на ~45..57 порядков МЕНЬШЕ требуемой
       экзотики горловины в GR (4πr0²ρ̄=−1/2 → |ρ|~5.4e27 кг/м³, ε~4.8e44 Дж/м³).
       QI-жизнь такой ячейки τ_FR~d/c ≈ 3e-16..3e-14 c.
   (B) Экзотика горловины в GR: QI допустима только на τ~3e-27 c — прямое
       указание, что GR-червоточина нежизнеспособна; f(T) при α<0 снимает
       само требование (q→1), и QI перестаёт быть активным для геометрии.
================================================================================
Параметры (конвенции R2): x=r/r0; T(x)=2(x−√(x²−1))²/x⁴ (BHL(16));
quad: f=T+αT² (α=T0·r0² безразмерно); power: f=T+λTⁿ.
Файл самодостаточен (numpy+scipy), печатает всё в __main__.
"""
import json
import numpy as np
from scipy.optimize import brentq

# ================================ константы (SI) =============================
hbar = 1.054571817e-34
c = 2.99792458e8
G = 6.67430e-11
pi = np.pi

R0 = 0.10                       # r0 (см. R1/R2), м
T_R0 = R0 / c                   # r0-единица времени, с
LP2 = G * hbar / c**3           # длина Планка², м²

C_QI = 3.0 * G * hbar / (8.0 * pi * c**3 * R0**2)   # RHS QI в 4πr0²-единицах
C_FR = (2160.0 / (32.0 * pi**4)) ** 0.25            # ≈0.9124, τ_FR = C_FR·d/c
R_CAS = 32.0 * pi**4 / 2160.0                       # 1.4431, R = R_CAS·(cτ/d)⁴

D_LIST = np.array([0.1e-6, 1.0e-6, 10.0e-6])          # d ∈ {0.1,1,10} мкм
X_THROAT = 1.0

# ============================ 1. Казимир и QI (SИ/r0) ========================
def eps_cas(d):
    """|ε| Казимира, Дж/м³ (>0)."""
    return pi**2 * hbar * c / (720.0 * d**4)

def rho_cas(d):
    """|ρ| массовая, кг/м³."""
    return eps_cas(d) / c**2

def rho_geom_bar(d):
    """4πr0²ρ̄(geom, G=c=1) — нормировка R2 для ячейки (>0)."""
    return 4.0 * pi * R0**2 * (G / c**2) * rho_cas(d)

def qi_eps_max(tau):
    """|ε|_max по QI, Дж/м³: 3ℏ/(32π²c³τ⁴)."""
    return 3.0 * hbar / (32.0 * pi**2 * c**3 * tau**4)

def qi_rho_geom_limit(tau_bar):
    """4πr0²·|ρ̄|_max по QI в r0-единицах: C_QI/τ̄⁴."""
    return C_QI / tau_bar**4

def sat_R(d, tau):
    """Коэффициент насыщения R = τ⁴|ρ|(32π²/3) [безразм.]: R_CAS·(cτ/d)⁴."""
    return R_CAS * (c * tau / d) ** 4

def tau_FR(d):
    """GR-предел (q=0): максимальное время жизни ячейки, с."""
    return C_FR * d / c

# ==================== 2. f(T): требуемая материя, good-тетрада ===============
def T16(x):
    u = np.sqrt(x * x - 1)
    return 2.0 * (x - u) ** 2 / x**4

def _field_matter(x, alpha, family='quad', lam=None, n=None):
    """4πr0²·(ρ,p_r,p_t) — BHL (18)-(20), good-тетрада (реплика ft2_necscan_BHL).
    Торсионный предел: α=0 → (−1/(2x⁴), −1/(2x⁴), +1/(2x⁴))."""
    u = np.sqrt(x * x - 1)
    T = T16(x)
    Tp = -4.0 * (x - u) ** 2 * (x + 2.0 * u) / (u * x**5)
    ebm = 1.0 - 1.0 / x**2
    al = np.sqrt(ebm)
    ebh = 1.0 / al
    xb_m1 = -(x * x + 1.0) / (x * x - 1.0)
    bp = -2.0 / (x * (x * x - 1.0))
    if family == 'quad':
        f, fT, fTT = T + alpha * T**2, 1.0 + 2.0 * alpha * T, 2.0 * alpha
    elif family == 'power':
        f, fT, fTT = (T + lam * T**n, 1.0 + lam * n * T ** (n - 1.0),
                      lam * n * (n - 1.0) * T ** (n - 2.0))
    else:
        raise ValueError(family)
    rho = (al / x) * (1.0 - al) * Tp * fTT - (T / 4.0 - 1.0 / (2.0 * x * x)) * fT \
          + (ebm / (2.0 * x * x)) * xb_m1 * fT + f / 4.0
    pr = (-1.0 / (2.0 * x * x) + T / 4.0 + ebm / (2.0 * x * x)) * fT - f / 4.0
    pt = (ebm / 2.0) * (1.0 / x - ebh / x) * Tp * fTT \
         + fT * (T / 4.0 + (ebm / (2.0 * x)) * (-0.5) * bp) - f / 4.0
    return rho, pr, pt

def rho_req(x, family='quad', alpha=None, lam=None, n=2.0):
    """Требуемая материальная плотность 4πr0²ρ(x). У горловины — аналит. предел."""
    if x == X_THROAT and family == 'quad':
        return -(1.0 + 22.0 * alpha) / 2.0
    return _field_matter(x, alpha if family == 'quad' else 0.0,
                         family, lam, n)[0]

def rho_GR(x):
    """TEGR=GR-предел экзотики, 4πr0²ρ_GR = −1/(2x⁴) (<0)."""
    return -1.0 / (2.0 * x**4)

def q_raw(x, family='quad', alpha=None, lam=None, n=2.0):
    """Доля экзотики, снятая торсионом: q = 1 − ρ_req/ρ_GR.
    q>0 — облегчение; q≥1 — требование экзотики снято полностью (ρ_req≥0)."""
    rr = rho_req(x, family, alpha, lam, n)
    return 1.0 - rr / rho_GR(x)

def q_eff(x, family='quad', alpha=None, lam=None, n=2.0):
    """q_raw, ограниченный снизу 0 (компенсация не ухудшает в разумном режиме)."""
    return max(0.0, min(q_raw(x, family, alpha, lam, n), 1.0))

# ========================= 3. Жизнеспособность ячейки =========================
def tau_avail(d, family='quad', alpha=None, lam=None, n=2.0, x=X_THROAT):
    """Максимальное время жизни отрицательной энергии ячейки d при f(T)-торсии."""
    q = q_eff(x, family, alpha, lam, n)
    if q >= 1.0:
        return np.inf
    return tau_FR(d) * (1.0 - q) ** -0.25

def life_factor(d, omega, family='quad', alpha=None, lam=None, n=2.0, x=X_THROAT):
    """Параметр для сканера: R_eff в пробе глубины τ=1/ω.
    R_eff = (1−q)·R_CAS·(c/(ωd))⁴.  Жизнеспособно при R_eff ≤ 1."""
    q = q_eff(x, family, alpha, lam, n)
    return (1.0 - q) * R_CAS * (c / (omega * d)) ** 4

def omega_QI(d, family='quad', alpha=None, lam=None, n=2.0, x=X_THROAT):
    """Минимальная частота пробы ω, при которой life_factor=1 (τ=τ_avail).
    Аналитически + перекрёстка brentq."""
    q = q_eff(x, family, alpha, lam, n)
    if q >= 1.0:
        return 0.0
    w_an = (c / d) * (R_CAS * (1.0 - q)) ** 0.25
    try:
        w_num = brentq(lambda w: life_factor(d, w, family, alpha, lam, n, x) - 1.0,
                       w_an * 1e-3, w_an * 1e3)
    except Exception:
        w_num = w_an
    return w_num

