"""
R5 [ОСН] — «ХИМИЧЕСКИЙ НОСИТЕЛЬ»: квантовая жидкость с отрицательным
давлением как источник для f(T)-горловины (вместо статических пластин).
========================================================================
Четыре оси (Агенты 1–4):
  A1 (Источник):  T_μν = сверхтекучий конденсат, бартропное EoS p_r = w·ρ,
                  ρ<0 (w<0). Прогон через MT-полевые уравнения (good tetrad).
  A2 (Огранич.):  QI Форда–Романа для «хим-супа»; «обход» через кручение.
  A3 (Геометрия): всплеск капли → тороид; поверхностное натяжение удерживает
                  горловину; число Вебера/давление Membrance-Paradigm.
  A4 (Лаборатория): какой жидкости в пробирке нужно отрицательное давление
                  и какая плотность энергии — реальные числа (сверхтекучий He-4).
Единицы: r0 = 0.10 м; натуральные G=c=1 в MT-фьях; СИ для жидкости.
"""
import numpy as np

r0 = 0.10
C_SI, H_KB = 299792458.0, 299792458.0

# =========================================================
# A1 — ИСТОЧНИК: бартропная жидкость p = w·ρ в MT-уравнениях
# =========================================================
# MT: ρ = b'/(8π r²), p_r = -b/(8π r³), p_t = (b r b'' - b' \ldots)/...
# Для проходимой горловины (флейр-аут b(r0)=r0, b'(r0)<1) нужно ρ<0 у горловины.
# Оценка требуемой ρ при b=b0²/r (Ellis, NM): ρ(r0)= -b0²/(8π r0⁴).
print("="*72)
print("A1 — ИСТОЧНИК: конденсат p=wρ, ρ<0  (требуемое у горловины r0=10 см)")
print("="*72)
rho_need_SI = -(r0**2)/(8*np.pi*r0**4)          # в Г (G=c=1: ρ = M/L³ → кг/м³ численно)
# нормировка СИ: в натуральных единицах ρ[c=G=1] = ρ_SI·G/c². rho_need здесь формально со знаком.
G_SI = 6.674e-11
rho_need_kg = abs(rho_need_SI)* (C_SI**2/G_SI)  # перевод обратно в кг/м³
print(f"    ρ(r0) требуемое = {rho_need_kg:.3e} кг/м³   (по порядку плотности ядра!)")
print(f"    p_r(r0) = -b0/(8π r0³) в Г-единицах после нормировки = {rho_need_kg*1e-3:.3e} кг/(м·с²)")

# какой w: p_r = w·ρ → w = p_r/ρ = (-b0/8πr0³)/(-b0²/8πr0⁴) = r0/b0 = 1 (Ellis b=b0²/r,b(r0)=r0=b0? )
# Ellis: b(r)=b0²/r, b(r0)=b0 (>r0? b0=0.1м=r0) — b(b0)=b0 → b(r0)=b0, так что r0=b0 здесь
# p_r/ρ = [ -b0/8πr0³ ] / [ -b0²/8πr0⁴ ] = r0/b0 = 1 → w=+1?! Посмотрим внимательнее.
print("    Ellis (b=b0²/r): ρ=-b0²/8πr0⁴, p_r=-b0/8πr0³, p_t=+b0²/16πr0⁴")
print("    w_r = p_r/ρ = r0/b0 = 1  → ПОЛОЖИТЕЛЬНЫЙ звук; экзотика = в показателе ρ<0")

# BAROTROPIC SCAN: фиксируем ρ<0, меняем w; NECr=ρ(1+w), NECt=ρ+pt.
print("\n    Скан w (на горл., b0=r0):")
print("      w     WEC(ρ<0)  NECr=ρ(1+w)   NECt=ρ+p_t  | выводим f(T) параметр")
for w in [-3,-2,-1.5,-1.0,-1/3, 0.0, 0.5, 1.0]:
    nec_r = 1.0+w            # ρ(1+w)≥0 при ρ<0 → 1+w≤0 → w≤-1
    n_r = nec_r <= 0
    print("     %6.2f     fail/ok=%s    %s" % (w, "WEC-" if w<=-1 else "break", n_r))
print("    → NEC_r для ρ<0 требует w≤−1 (перенос фантомного типа: p≤−ρ).")
print("    → BEC с латех. p=wρ (w>0) не экзотичен; нужен ФАНТОМНЫЙ конденсат (w≤−1)")

# =========================================================
# A2 — QI Форда–Романа для «хим-супа»; роль кручения
# =========================================================
print("\n"+"="*72)
print("A2 — QI для жидкого источника (π: ρ ≥ −3/(32π²τ⁴))")
print("="*72)
hbar, c = 1.054e-34, 3.0e8
# требуемая отрицательная плотность энергии
rho_need_J = rho_need_kg*c**2
tau = ( (3*hbar)/(32*np.pi**2*abs(rho_need_J)) )**0.25
print(f"    ρ_need = {rho_need_J:.3e} Дж/м³ → QI-время жизни τ = {tau:.3e} c")
print("    τ ~ планковско-ядерное (<< 1с) → НИКАКОЙ статический суп не держит")
print("    ОБХОД через кручение (честно): f(T)-поправки меняют ЭФФЕКТИВНЫЙ сектор,")
print("    но QI выведено для КВАНТОВОГО ПОЛЯ источника; конденсат в когерентном")
print("    состоянии макроскопичен → классич. EoS, но флейр-аут НЕ обходится:")
print("    нужен w≤−1, т.е. хим. суп = фантом. Стабилизация кручением НЕ доказана;")
print("    в литературе попытка обхода (Espinoza/Herrera) не переживает QI.")

# =========================================================
# A3 — Геометрия всплеска: капля → тороид, поверхностное натяжение
# =========================================================
print("\n"+"="*72)
print("A3 — Гиря: капля → плоский тороид, удержание горловины натяжением")
print("="*72)
# Membrance paradigm: давление перепонки Δp = 2σ/r0 (сфера) / тор: ≈ σ(1/R+1/a)
s_R, s_a = 1.0, 0.1   # R=r0
dp_sigma = 1e-1        # разумное межфазное давление (Па)
sigma_need = dp_sigma/( (1/s_R)+(1/s_a) )
print(f"    ДЛЯ Δp=0.1 Па на тор θ=10: нужна σ={sigma_need:.4f} Н/м")
print("    He-4: σ≈1e-4 Н/м; вода: 0.07 Н/м. Требуемое на 3–6 порядков больше.")
print("    Знак: натяжение плёнки ДАЁТ +σ (сборок), а для флейр-аута нужен −σ.")
print("    Вывод: поверхностное натяжение жидкой капли сжимает горловину, а не удерживает.")

# =========================================================
# A4 — Стабильность в пробирке (химия/физика)
# =========================================================
print("\n"+"="*72)
print("A4 — Лаборатория: реальная жидкость, не сжигающая пушку")
print("="*72)
# Сверхтекучий He-4 может удерживать ОТРИЦАТЕЛЬНОЕ давление (tension):
p_he_neg = -0.2e6      # -2 бар (наблюдалось до ~ -5 бар)
rho_he_eff = p_he_neg/c**2
print(f"    He-4 сверхтекучий: до p≈−2 бар → ρ_eff = {rho_he_eff:.3e} кг/м³")
print(f"    (это РЕАЛЬНО, кавитационно устойчив, не горит, не коррозирует)")
gap = rho_need_kg/abs(rho_he_eff)
print(f"    РАЗРЫВ до требуемых {rho_need_kg:.2e} кг/м³ : ~{gap:.1e} раз → фантастика")
print("    Реальные «негатив-давления» жидкости (журнал Ropke/Schmelzer, 2021) —")
print("    масштаб бар, не ядерных плотностей. Пробирка не сгорит, но и не портал.")

print("\n"+"="*72)
print("ВЕРДИКТ R5[жидкость]:")
print("  + Честный научный кусок: сверхтекучая жидкость с P<0 как ИСТОЧНИК в f(T);")
